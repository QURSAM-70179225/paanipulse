const DICTS: Record<Lang, Record<DictKey, string>> = { en, ur };

export function t(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export const isLang = (x: unknown): x is Lang => x === "ur" || x === "en";
export const dirFor = (lang: Lang) => (lang === "ur" ? "rtl" : "ltr");

/** Whole dictionary for one language (for client components). */
export const dictFor = (lang: Lang) => DICTS[lang];
export const fill = (s: string, vars: Record<string, string | number>) =>
  Object.entries(vars).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)), s);
